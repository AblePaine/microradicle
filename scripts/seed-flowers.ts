type Geom = Crop["fieldGeometry"];
type Irr = Crop["irrigationProfile"];
type Store = Omit<CropPostHarvestSpec, "crop_id">;

function geom(rows: 1 | 2 | 3 | 4 | 5 | 6, inRow: number): Geom {
  const plants = Math.round(rows * (12 / inRow) * 100) / 100;
  return {
    standardBedWidthIn: 30,
    rowsPerBed: rows,
    inRowSpacingIn: inRow,
    seedSpacingIn: Math.min(2, Math.max(0.5, inRow / 4)),
    plantsPerLinearFoot: plants,
  };
}

function irr(weekIn: number, lines: 1 | 2 | 3 | 4 = 2): Irr {
  return { linesPerBed: lines, emitterSpacingIn: 8, emitterGph: 0.42, weeklyWaterRequirementIn: weekIn };
}

