function expand(species: SpeciesKey, v: Variant): Crop {
  const t = S[species];
  const flower: CutFlowerSpecifics = {
    ...t.flower,
    primaryUse: v.use ?? t.flower.primaryUse,
  };
  const dtm = (v.dtm ?? t.dtm) + (flower.pinching.required ? flower.pinching.dtmPenaltyDays : 0);
  return {
    id: v.id,
    commonName: t.commonName,
    cultivar: v.cultivar,
    botanicalName: t.botanicalName,
    family: t.family,
    category: "cut-flowers",
    flowerSpecifics: flower,
    propagation: {
      method: t.method,
      recommendedCellSize: t.cell,
      nurseryLeadDays: t.nursery,
      germinationDays: t.germDays,
      minGermTempF: t.germMin,
      optimumGermTempF: t.germOpt,
      maxGermTempF: t.germMax,
    },
    fieldGeometry: t.geom,
    timeline: {
      dtmFromField: dtm,
      fieldHoldingDays: t.holding,
      isMulticut: t.harvests > 1,
      regrowthDays: t.harvests > 1 ? Math.max(3, flower.harvestProtocol.cutFrequencyDays) : null,
      maxHarvests: t.harvests,
      fallPhotoperiodMultiplier: 1,
      frostHardiness: t.frost,
    },
    yieldAndRevenue: {
      salesUnit: "stem",
      unitsPerBedFoot: t.unitsFt,
      avgWeightPerUnitLbs: t.ozUnit,
      targetYieldLbsPerBedFoot: t.lbsFt,
      standardCullRate: t.cull,
      targetWholesalePriceUsd: v.whole ?? t.whole,
      targetDirectPriceUsd: v.direct ?? t.direct,
    },
    irrigationProfile: t.irr,
    soilExtractionProfile: {
      fertilityDemand: t.n >= 1.8 ? "heavy" : t.n <= 1.1 ? "light" : "moderate",
      nRemovalLbsPer100BedFt: t.n,
      pRemovalLbsPer100BedFt: t.p,
      kRemovalLbsPer100BedFt: t.k,
    },
    successionIntervalDays: t.interval,
    maxSuccessions: t.maxSucc,
    companions: ["basil", "dill", "alyssum"],
    avoid: ["fennel"],
    notes: v.notes ?? t.notes,
    swatch: v.swatch ?? t.swatch,
  };
}

export const FLOWER_DATABASE: Crop[] = VARIANTS.map((row) => expand(row.species, row));

function isMain(): boolean {
  const self = fileURLToPath(import.meta.url);
  const invoked = process.argv[1] ? join(process.argv[1]) : "";
  return self === invoked || invoked.endsWith("seed-flowers.ts");
}

export function seedFlowers(): { written: number; skipped: number; specs: number; flowers: number } {
  if (!existsSync(cropDir)) mkdirSync(cropDir, { recursive: true });
  const ids = new Set<string>();
  let written = 0;
  let skipped = 0;
  const newSpecs: CropPostHarvestSpec[] = [];

  for (const row of VARIANTS) {
    if (ids.has(row.id)) throw new Error(`Duplicate flower id: ${row.id}`);
    ids.add(row.id);
    const crop = expand(row.species, row);
    const file = join(cropDir, `${crop.id}.json`);
    if (existsSync(file)) {
      const existing = JSON.parse(readFileSync(file, "utf8")) as { category?: string };
      if (existing.category !== "cut-flowers") {
        skipped += 1;
        continue;
      }
    }
    writeFileSync(file, `${JSON.stringify(crop, null, 2)}\n`, "utf8");
    written += 1;
    newSpecs.push({ crop_id: crop.id, ...S[row.species].store });
  }

  const existing: CropPostHarvestSpec[] = existsSync(storagePath)
    ? (JSON.parse(readFileSync(storagePath, "utf8")) as CropPostHarvestSpec[])
    : [];
  const specById = new Map(existing.map((s) => [s.crop_id, s]));
  for (const spec of newSpecs) {
    if (!specById.has(spec.crop_id)) specById.set(spec.crop_id, spec);
  }
  const specs = [...specById.values()].sort((a, b) => a.crop_id.localeCompare(b.crop_id));
  writeFileSync(storagePath, `${JSON.stringify(specs, null, 2)}\n`, "utf8");

  return { written, skipped, specs: specs.length, flowers: VARIANTS.length };
}

if (isMain()) {
  const result = seedFlowers();
  console.log(
    `Seeded ${result.written} cut-flower files (${result.skipped} vegetable collisions skipped). Flowers in seed: ${result.flowers}. Storage specs: ${result.specs}.`,
  );
}
