function net(
  required: boolean,
  layers: 1 | 2,
  mesh: 6 | 8,
  first: number,
  second: number | null,
): CutFlowerSpecifics["supportNetting"] {
  return {
    required,
    layers,
    meshSizeIn: mesh,
    firstLayerHeightIn: first,
    secondLayerHeightIn: second,
  };
}

function pinch(
  required: boolean,
  height: number,
  nodes: number,
  penalty: number,
): CutFlowerSpecifics["pinching"] {
  return {
    required,
    pinchAtHeightIn: height,
    leaveNodeCount: nodes,
    dtmPenaltyDays: penalty,
  };
}

function harvest(
  stage: FlowerHarvestStage,
  freq: number,
  perPlant: number,
  perFt: number,
  pulse: PostHarvestPulse,
  vase: number,
): CutFlowerSpecifics["harvestProtocol"] {
  return {
    stage,
    cutFrequencyDays: freq,
    stemsPerPlant: perPlant,
    stemsPerLinearBedFoot: perFt,
    recommendedPulse: pulse,
    vaseLifeDays: vase,
  };
}

