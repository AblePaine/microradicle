#!/usr/bin/env node
/**
 * Generate public/sitemap.xml from the route tree + data files.
 *
 * Static routes are derived by walking src/routes (TanStack file routing:
 * `index.tsx` -> parent path, `foo.bar.tsx` -> `/foo/bar`). Dynamic `$slug`
 * routes are expanded from their data source (see DYNAMIC_SOURCES); any
 * `$` route without a declared source aborts the build so a new dynamic
 * route is a conscious decision, not a silent sitemap omission.
 *
 * Runs on every `npm run build` via the `prebuild` lifecycle script, so the
 * sitemap tracks the data (e.g. a new cultivar JSON) with no hand edits.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { basename, join, relative } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = fileURLToPath(new URL("..", import.meta.url));
const ROUTES_DIR = join(ROOT, "src", "routes");
const OUT_FILE = join(ROOT, "public", "sitemap.xml");
const SITE_URL = "https://www.microradicle.com";

/** Files that are redirect aliases (client-side <Navigate>) or the root shell — never listed. */
const SKIP_FILES = new Set(["__root.tsx", "clip.tsx", "print.clipboard.tsx"]);

function readJson(path) {
  return JSON.parse(readFileSync(path, "utf8"));
}

function cropSlugs() {
  const dir = join(ROOT, "src", "data", "crops");
  return readdirSync(dir)
    .filter((f) => f.endsWith(".json"))
    .map((f) => readJson(join(dir, f)).id ?? basename(f, ".json"));
}

function dataIds(relPath) {
  return readJson(join(ROOT, relPath)).map((row) => row.id);
}

function storageZoneSlugs() {
  // All zones the route can render (STORAGE_ZONES in economics-calc.ts),
  // unioned with the zones actually used by the specs data — a zone with no
  // crops assigned yet (e.g. zone-curing) still has a public page.
  const specs = readJson(join(ROOT, "src", "data", "economics", "storageSpecs.json"));
  const zones = new Set(specs.map((s) => s.storage_zone));
  const calcSrc = readFileSync(join(ROOT, "src", "lib", "economics-calc.ts"), "utf8");
  const block = /STORAGE_ZONES[^=]*=\s*\[([^\]]*)\]/.exec(calcSrc)?.[1] ?? "";
  for (const m of block.matchAll(/"([^"]+)"/g)) zones.add(m[1]);
  return [...zones];
}

/**
 * Dynamic route path -> slug enumerator. `/soil/$slug`, `/irrigation/$slug`
 * and `/feed/$slug` are intentionally absent: their slugs are per-user farm
 * entities (blocks, zones, saved rations) from the local farm store, so they
 * have no public canonical URLs to list.
 */
const DYNAMIC_SOURCES = {
  "/crop": () => cropSlugs(),
  "/economics": () => [...cropSlugs(), ...storageZoneSlugs()],
  "/nursery": () => dataIds("src/data/nursery/microgreens.json"),
  "/pasture": () => dataIds("src/data/pasture/species.json"),
};
const USER_STATE_DYNAMIC = new Set(["/soil", "/irrigation", "/feed"]);

function walk(dir) {
  const out = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else if (entry.name.endsWith(".tsx")) out.push(full);
  }
  return out;
}

function fileToRoutePath(file) {
  const rel = relative(ROUTES_DIR, file).replace(/\.tsx$/, "");
  const parts = rel.split("/").flatMap((part) => part.split("."));
  if (parts[parts.length - 1] === "index") parts.pop();
  return `/${parts.join("/")}`.replace(/\/$/, "") || "/";
}

const urls = new Set();
for (const file of walk(ROUTES_DIR)) {
  if (SKIP_FILES.has(basename(file))) continue;
  const routePath = fileToRoutePath(file);
  if (!routePath.includes("$")) {
    urls.add(routePath === "/" ? `${SITE_URL}/` : `${SITE_URL}${routePath}`);
    continue;
  }
  const parent = routePath.replace(/\/\$[^/]+$/, "");
  const source = DYNAMIC_SOURCES[parent];
  if (source) {
    for (const slug of source()) urls.add(`${SITE_URL}${parent}/${slug}`);
  } else if (!USER_STATE_DYNAMIC.has(parent)) {
    throw new Error(
      `generate-sitemap: no slug source declared for dynamic route ${routePath}. ` +
        "Add it to DYNAMIC_SOURCES or USER_STATE_DYNAMIC in scripts/generate-sitemap.mjs.",
    );
  }
}

const sorted = [...urls].sort();
const xml = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  "<!-- Generated by scripts/generate-sitemap.mjs from src/routes + src/data. Do not hand-edit. -->",
  '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
  ...sorted.map((loc) => `  <url><loc>${loc}</loc></url>`),
  "</urlset>",
  "",
].join("\n");

writeFileSync(OUT_FILE, xml);
console.log(`[generate-sitemap] wrote ${sorted.length} URLs to public/sitemap.xml`);
