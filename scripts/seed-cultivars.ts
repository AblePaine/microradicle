function expand(species: SpeciesKey, v: Variant): Crop {
  const t = S[species];
  const unitsFt = v.unitsFt ?? t.unitsFt;
  const lbsFt = v.lbsFt ?? t.lbsFt;
  return {
    id: v.id,
    commonName: v.commonName ?? t.commonName,
    cultivar: v.cultivar,
    botanicalName: v.botanicalName ?? t.botanicalName,
    family: v.family ?? t.family,
    category: t.category,
    propagation: {
      method: t.method,
      recommendedCellSize: t.cell,
      nurseryLeadDays: t.nursery,
      germinationDays: t.germDays,
      minGermTempF: t.germMin,
      optimumGermTempF: t.germOpt,
      maxGermTempF: t.germMax,
    },
    fieldGeometry: t.geom,
    timeline: {
      dtmFromField: v.dtm ?? t.dtm,
      fieldHoldingDays: v.holding ?? t.holding,
      isMulticut: t.multicut,
      regrowthDays: t.regrowth,
      maxHarvests: t.harvests,
      fallPhotoperiodMultiplier: t.fall,
      frostHardiness: v.frost ?? t.frost,
    },
    yieldAndRevenue: {
      salesUnit: t.unit,
      unitsPerBedFoot: unitsFt,
      avgWeightPerUnitLbs: t.ozUnit,
      targetYieldLbsPerBedFoot: lbsFt,
      standardCullRate: t.cull,
      targetWholesalePriceUsd: v.whole ?? t.whole,
      targetDirectPriceUsd: v.direct ?? t.direct,
    },
    irrigationProfile: t.irr,
    soilExtractionProfile: {
      fertilityDemand: t.demand,
      nRemovalLbsPer100BedFt: t.n,
      pRemovalLbsPer100BedFt: t.p,
      kRemovalLbsPer100BedFt: t.k,
    },
    successionIntervalDays: t.interval,
    maxSuccessions: t.maxSucc,
    companions: t.companions,
    avoid: t.avoid,
    notes: v.notes ?? t.notes,
    swatch: v.swatch ?? t.swatch,
  };
}

export const CULTIVAR_DATABASE: Crop[] = VARIANTS.map((row) => expand(row.species, row));

function storageFor(crop: Crop, species: SpeciesKey): CropPostHarvestSpec {
  return { crop_id: crop.id, ...S[species].store };
}

function isMain(): boolean {
  const self = fileURLToPath(import.meta.url);
  const invoked = process.argv[1] ? join(process.argv[1]) : "";
  return self === invoked || invoked.endsWith("seed-cultivars.ts");
}

export function seedCultivars(): { written: number; preserved: number; specs: number; totalOnDisk: number } {
  if (!existsSync(cropDir)) mkdirSync(cropDir, { recursive: true });

  const ids = new Set<string>();
  for (const id of PRESERVE_IDS) ids.add(id);
  let written = 0;
  let preserved = 0;
  const newSpecs: CropPostHarvestSpec[] = [];

  for (const row of VARIANTS) {
    if (ids.has(row.id)) throw new Error(`Duplicate cultivar id: ${row.id}`);
    ids.add(row.id);
    const crop = expand(row.species, row);
    const file = join(cropDir, `${crop.id}.json`);
    if (PRESERVE.has(crop.id) && existsSync(file)) {
      preserved += 1;
      continue;
    }
    writeFileSync(file, `${JSON.stringify(crop, null, 2)}\n`, "utf8");
    written += 1;
    newSpecs.push(storageFor(crop, row.species));
  }

  const existing: CropPostHarvestSpec[] = existsSync(storagePath)
    ? (JSON.parse(readFileSync(storagePath, "utf8")) as CropPostHarvestSpec[])
    : [];
  const specById = new Map(existing.map((s) => [s.crop_id, s]));
  for (const spec of newSpecs) {
    if (!specById.has(spec.crop_id)) specById.set(spec.crop_id, spec);
  }

  const onDisk = readdirSync(cropDir).filter((f) => f.endsWith(".json"));
  for (const file of onDisk) {
    const crop = JSON.parse(readFileSync(join(cropDir, file), "utf8")) as Crop;
    if (!specById.has(crop.id)) {
      const row = VARIANTS.find((v) => v.id === crop.id);
      const species = row?.species ?? "lettuceHead";
      specById.set(crop.id, storageFor(crop, species));
    }
  }

  const specs = [...specById.values()].sort((a, b) => a.crop_id.localeCompare(b.crop_id));
  writeFileSync(storagePath, `${JSON.stringify(specs, null, 2)}\n`, "utf8");

  return { written, preserved, specs: specs.length, totalOnDisk: onDisk.length };
}

if (isMain()) {
  const result = seedCultivars();
  console.log(
    `Seeded ${result.written} new cultivar files (${result.preserved} preserved). Catalog on disk: ${result.totalOnDisk}. Storage specs: ${result.specs}.`,
  );
}
