function r2(n: number): number {
  return Math.round(n * 100) / 100;
}

function geom(rows: 1 | 2 | 3 | 4 | 5 | 6, inRow: number, seed = inRow): Geom {
  return {
    standardBedWidthIn: 30,
    rowsPerBed: rows,
    inRowSpacingIn: inRow,
    seedSpacingIn: seed,
    plantsPerLinearFoot: r2(rows * (12 / inRow)),
  };
}

function irr(lines: 1 | 2 | 3 | 4, spacing: 4 | 8 | 12, gph: 0.25 | 0.42 | 0.5 | 0.65, weekIn: number): Irr {
  return { linesPerBed: lines, emitterSpacingIn: spacing, emitterGph: gph, weeklyWaterRequirementIn: weekIn };
}

function store(
  zone: StorageThermalZone,
  opt: number,
  min: number,
  max: number,
  rh: number,
  days: number,
  cool: CoolingMethod,
  resp: RespirationRating,
  cp: number,
  totes: number,
  hours: number,
): Store {
  return {
    storage_zone: zone,
    optimal_temp_f: opt,
    min_safe_temp_f: min,
    max_temp_f: max,
    optimal_rh_pct: rh,
    shelf_life_days: days,
    cooling_method: cool,
    respiration_rate_rating: resp,
    sensible_heat_btu_per_lb: cp,
    totes_per_100_lbs: totes,
    harvest_hours_per_100_bed_ft: hours,
  };
}

